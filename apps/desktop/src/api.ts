import { invoke } from "@tauri-apps/api/core";
import type { AssistantState, BrainNudge, BrainPromise, ChatThread, CollectionImportPreview, CollectionItem, EngineSettings, JournalDayData, JournalDaySummary, JournalEntry, Meeting, ModelHealth, OrbitPerson, PersonDetails, PersonPage, Project, ResearchPreferences, Routine, RoutineRun, Trip } from "./types";

export interface SetupStatus { configured: boolean; gpu?: string; vramMb?: number; supported: boolean; reason: string; totalBytes: number; running: boolean }
export interface SetupProgress { key: string; label: string; phase: string; done: number; total: number }
export interface AppUpdate { current: string; latest?: string; available: boolean; error?: string }
export interface ModelUpdate { installed?: string; available: boolean; name?: string; error?: string }

export const api = {
  setupStatus: () => invoke<SetupStatus>("setup_status"),
  runSetup: () => invoke<void>("run_setup"),
  checkAppUpdate: () => invoke<AppUpdate>("check_app_update"),
  installAppUpdate: () => invoke<void>("install_app_update"),
  checkModelUpdate: () => invoke<ModelUpdate>("check_model_update"),
  updateModel: () => invoke<void>("update_model"),
  meetings: () => invoke<Meeting[]>("list_meetings"),
  meeting: (id: string) => invoke<Meeting>("get_meeting", { id }),
  includeInBrain: (folder: string, included: boolean) => invoke("set_include_in_brain", { folder, included }),
  deleteMeeting: (folder: string) => invoke("delete_meeting", { folder }),
  orbit: () => invoke<OrbitPerson[]>("brain_orbit"),
  addPerson: (name: string, world: string, summary: string, email: string) => invoke("brain_add_person", { name, world, summary, email }),
  person: (name: string) => invoke<PersonPage | null>("brain_person", { name }),
  setPersonCloseness: (name: string, level?: number) => invoke("brain_set_closeness", { name, level: level ?? null }),
  updatePersonDetails: (name: string, value: PersonDetails) => invoke("brain_update_details", { name, value }),
  forgetPerson: (name: string) => invoke("brain_forget_person", { name }),
  nudges: () => invoke<BrainNudge[]>("brain_nudges"),
  promises: () => invoke<BrainPromise[]>("brain_promises"),
  personChatCreate: (name: string) => invoke<string>("person_chat_create", { name }),
  personChatIds: (name: string) => invoke<string[]>("person_chat_ids", { name }),
  personChatDelete: (name: string, id: string) => invoke("person_chat_delete", { name, id }),
  sendPersonChat: (threadId: string, person: string, question: string) => invoke<{ answer: string; sources: string[]; status: string }>("send_person_chat", { threadId, person, question }),
  projects: () => invoke<Project[]>("projects_list"),
  createProject: (name: string, instructions: string) => invoke<Project>("project_create", { name, instructions }),
  updateProjectInstructions: (projectId: string, instructions: string) => invoke<Project>("project_update_instructions", { projectId, instructions }),
  setProjectInclude: (projectId: string, included: boolean) => invoke<Project>("project_set_include", { projectId, included }),
  setProjectFileInclude: (projectId: string, fileId: string, included: boolean) => invoke<Project>("project_set_file_include", { projectId, fileId, included }),
  addProjectFile: (projectId: string, name: string, size: number, type: string, text: string) => invoke<Project>("project_add_file", { projectId, name, size, fileType: type, text }),
  removeProjectFile: (projectId: string, fileId: string) => invoke<Project>("project_remove_file", { projectId, fileId }),
  deleteProject: (projectId: string) => invoke("project_delete", { projectId }),
  createProjectChat: (projectId: string) => invoke<string>("project_create_chat", { projectId }),
  deleteProjectChat: (projectId: string, threadId: string) => invoke("project_delete_chat", { projectId, threadId }),
  sendProjectChat: (threadId: string, projectId: string, question: string) => invoke<{ answer: string; sources: string[]; status: string }>("send_project_chat", { threadId, projectId, question }),
  routines: () => invoke<Routine[]>("routines_list"),
  saveRoutine: (routine: Routine) => invoke<Routine>("routine_save", { routine }),
  deleteRoutine: (id: string) => invoke("routine_delete", { id }),
  runRoutine: (id: string) => invoke<RoutineRun>("routine_run_now", { id }),
  threads: () => invoke<ChatThread[]>("list_threads"),
  thread: (id: string) => invoke<ChatThread | null>("get_thread", { id }),
  createThread: (id?: string) => invoke<ChatThread>("create_thread", { id }),
  renameThread: (id: string, title: string) => invoke("rename_thread", { id, title }),
  deleteThread: (id: string) => invoke("delete_thread", { id }),
  markSeen: (id: string, count: number) => invoke("mark_seen", { id, count }),
  sendChat: (threadId: string, question: string) => invoke<{ answer: string; sources: string[]; status: string }>("send_thread_message", { threadId, question }),
  assistant: () => invoke<AssistantState>("assistant_profile"),
  assistantAction: (action: string) => invoke<AssistantState>("assistant_action", { action }),
  updateAssistant: (name: string, emoji: string) => invoke<AssistantState>("update_assistant", { name, emoji }),
  researchPreferences: () => invoke<ResearchPreferences>("research_preferences"),
  saveResearchPreferences: (prefs: ResearchPreferences) => invoke("save_research_preferences", { ...prefs }),
  engineSettings: () => invoke<EngineSettings>("engine_settings"),
  modelHealth: () => invoke<ModelHealth>("model_health"),
  openSettingsFolder: () => invoke("open_settings_folder"),
  startRecording: () => invoke<string>("start_recording"),
  stopRecording: () => invoke("stop_recording"),
  collection: (kind: string) => invoke<CollectionItem[]>("list_collection", { kind }),
  saveCollection: (item: CollectionItem, originalKind?: string) => invoke<CollectionItem>("save_collection_item", { item, original_kind: originalKind }),
  deleteCollection: (item: CollectionItem) => invoke("delete_collection_item", { item }),
  setCollectionInclude: (item: CollectionItem, included: boolean) => invoke<CollectionItem>("set_collection_include_in_brain", { item, included }),
  addCollectionByLink: (url: string) => invoke<CollectionItem>("add_collection_by_link", { url }),
  importCollection: (kind: string, source: string, text: string) => invoke<CollectionImportPreview>("import_collection", { kind, source, text }),
  collectionCover: (item: CollectionItem) => invoke<number[] | null>("collection_cover_data", { item }),
  trips: () => invoke<Trip[]>("list_trips"),
  saveTrip: (trip: Trip) => invoke<Trip>("save_trip_command", { trip }),
  deleteTrip: (trip: Trip) => invoke("delete_trip_command", { trip }),
  setTripInclude: (trip: Trip, included: boolean) => invoke<Trip>("set_trip_include_in_brain", { trip, included }),
  tripPhoto: (trip: Trip, name: string) => invoke<number[] | null>("trip_photo_data", { trip, name }),
  addTripPhoto: (trip: Trip, name: string, data: number[], extension: string) => invoke<Trip>("add_trip_photo", { trip, name, data, extension }),
  journalDays: () => invoke<JournalDaySummary[]>("list_journal_days"),
  journalDay: (day: string) => invoke<JournalDayData>("get_journal_day", { day }),
  saveJournal: (entry: JournalEntry) => invoke<JournalEntry>("save_journal_entry", { entry }),
  rewriteJournal: (day: string, force: boolean) => invoke<JournalEntry>("rewrite_journal", { day, force }),
  saveRoutineResult: (name: string, result: string, date?: string) => invoke<JournalEntry>("save_routine_result", { name, result, date })
};
